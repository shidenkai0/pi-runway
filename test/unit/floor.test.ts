test('floor catches every always-ask command', () => {
  const wrong = MUST_ASK.filter(([command, id]) => checkFloor(command)?.id !== id).map(([command, id]) => `${command} -> ${checkFloor(command)?.id ?? 'none'} (want ${id})`)
  assert.deepEqual(wrong, [])
})

test('floor leaves ordinary escalations to the reviewer', () => {
  const misfires = REVIEWER_DECIDES.filter(c => checkFloor(c)).map(c => `${c} -> ${checkFloor(c)?.id}`)
  assert.deepEqual(misfires, [])
})

test('trustedCommands skip the floor', () => {
  assert.ok(checkFloor('npm publish --tag next'))
  assert.equal(checkFloor('npm publish --tag next', ['npm publish --tag next']), undefined)
  assert.ok(checkFloor('npm publish --tag next && sudo reboot', ['npm publish --tag next']), 'trust does not cover chained commands')
})

test('table size', () => {
  assert.ok(MUST_ASK.length + REVIEWER_DECIDES.length >= 130)
})
